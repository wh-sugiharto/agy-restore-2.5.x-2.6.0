#!/usr/bin/env python3
"""
execute_backfill.py

Phase 2 of Antigravity 2.5.x -> 2.6.0 Migration:
- Reads `scratch_file.yml` generated by `check_and_catalog.py`.
- Copies missing conversations/*.db files.
- Copies missing brain/<id> folders faithfully.
- Backfills project IDs into conversation_summaries.db and agyhub_summaries_proto.pb.
- Supports --migrate-unmarked (experimental) to handle sessions without .done markers.
"""

import os
import sys
import shutil
import sqlite3
import json
import argparse
import subprocess
from typing import Dict, Any
import yaml
import blackboxprotobuf

DEFAULT_OLD_IDE_DIR = os.path.expanduser("~/.gemini/antigravity-ide")
DEFAULT_DESTINATION_DIR = os.path.expanduser("~/.gemini/antigravity")
DEFAULT_MANIFEST = "scratch_file.yml"

def parse_args():
    parser = argparse.ArgumentParser(description="Antigravity Migration: Execute Backfill")
    parser.add_argument("--manifest", default=DEFAULT_MANIFEST, help="Path to manifest YAML file (default: scratch_file.yml)")
    parser.add_argument("--old-ide-dir", default=DEFAULT_OLD_IDE_DIR, help="Path to 2.5.x antigravity-ide source directory")
    parser.add_argument("--destination-dir", default=DEFAULT_DESTINATION_DIR, help="Path to 2.6.0 destination directory")
    parser.add_argument("--migrate-unmarked", action="store_true", help="Experimental: Migrate conversations lacking .done markers")
    parser.add_argument("--skip-backup", action="store_true", help="Skip creating safety backups")
    return parser.parse_args()

def check_process_not_running():
    try:
        if sys.platform == "win32":
            res = subprocess.run(["tasklist"], stdout=subprocess.PIPE, text=True, errors="replace")
            if "Antigravity.exe" in res.stdout or "antigravity.exe" in res.stdout:
                print("ERROR: Antigravity Desktop is currently running!", file=sys.stderr)
                print("Please quit Antigravity Desktop completely before running execute_backfill.py.", file=sys.stderr)
                sys.exit(1)
        else:
            res = subprocess.run(["pgrep", "-f", "antigravity"], stdout=subprocess.PIPE, text=True)
            if res.returncode == 0:
                pids = res.stdout.strip().splitlines()
                desktop_running = False
                for pid in pids:
                    try:
                        with open(f"/proc/{pid}/cmdline", "r") as f:
                            cmd = f.read()
                            if "remote-control serve" not in cmd and "execute_backfill" not in cmd and "check_and_catalog" not in cmd:
                                desktop_running = True
                                break
                    except Exception:
                        desktop_running = True
                if desktop_running:
                    print("ERROR: Antigravity Desktop is currently running!", file=sys.stderr)
                    print("Please quit Antigravity Desktop completely before running execute_backfill.py.", file=sys.stderr)
                    sys.exit(1)
    except FileNotFoundError:
        pass
    print("✓ Process check passed: Antigravity Desktop is closed.")

def copy_missing_files(old_dir: str, dest_dir: str):
    print("\n--- 1. Copying Missing Files ---")
    # 1. Missing conversations/*.db
    old_conv_dir = os.path.join(old_dir, "conversations")
    dest_conv_dir = os.path.join(dest_dir, "conversations")
    os.makedirs(dest_conv_dir, exist_ok=True)

    copied_dbs = 0
    if os.path.isdir(old_conv_dir):
        old_dbs = {f for f in os.listdir(old_conv_dir) if f.endswith(".db")}
        dest_dbs = {f for f in os.listdir(dest_conv_dir) if f.endswith(".db")}
        missing_dbs = old_dbs - dest_dbs

        for f in sorted(missing_dbs):
            shutil.copy2(os.path.join(old_conv_dir, f), os.path.join(dest_conv_dir, f))
            copied_dbs += 1
    print(f"✓ Copied {copied_dbs} missing conversations/*.db files.")

    # 2. Missing brain/<id> folders
    old_brain_dir = os.path.join(old_dir, "brain")
    dest_brain_dir = os.path.join(dest_dir, "brain")
    os.makedirs(dest_brain_dir, exist_ok=True)

    copied_brains = 0
    if os.path.isdir(old_brain_dir):
        old_brains = set(os.listdir(old_brain_dir))
        dest_brains = set(os.listdir(dest_brain_dir))
        missing_brains = old_brains - dest_brains

        for b in sorted(missing_brains):
            src_path = os.path.join(old_brain_dir, b)
            dst_path = os.path.join(dest_brain_dir, b)
            if os.path.isdir(src_path):
                shutil.copytree(src_path, dst_path, dirs_exist_ok=True)
                copied_brains += 1
    print(f"✓ Copied {copied_brains} missing brain/<id> folders.")

def handle_unmarked_conversations(old_dir: str, dest_dir: str, con: sqlite3.Connection):
    """Experimental: Indexes sessions from source that were not marked with .done."""
    print("\n--- (Experimental) Handling Unmarked Conversations ---")
    old_conv_dir = os.path.join(old_dir, "conversations")
    if not os.path.isdir(old_conv_dir):
        return

    old_dbs = {f[:-3] for f in os.listdir(old_conv_dir) if f.endswith(".db")}
    old_dones = {f[1:-5] for f in os.listdir(old_conv_dir) if f.startswith(".") and f.endswith(".done")}
    unmarked = old_dbs - old_dones

    if not unmarked:
        print("No unmarked conversations found.")
        return

    print(f"Found {len(unmarked)} conversations without .done marker.")
    cur = con.cursor()
    newly_indexed = 0

    for cid in sorted(unmarked):
        # Check if already in destination DB
        exists = cur.execute("SELECT 1 FROM conversation_summaries WHERE conversation_id = ?", (cid,)).fetchone()
        if not exists:
            # Insert stub entry
            cur.execute("""
                INSERT INTO conversation_summaries (conversation_id, title, preview, last_modified_time, last_user_input_time, workspace_uris)
                VALUES (?, '', '', datetime('now'), datetime('now'), '[]')
            """, (cid,))
            newly_indexed += 1

        # Touch .done marker
        done_file = os.path.join(old_conv_dir, f".{cid}.done")
        try:
            with open(done_file, "a"):
                os.utime(done_file, None)
        except Exception:
            pass

    con.commit()
    print(f"Indexed {newly_indexed} unmarked conversations into SQLite.")

def apply_project_backfill(dest_dir: str, manifest_path: str, con: sqlite3.Connection):
    print("\n--- 2. Applying Project Backfill ---")
    with open(manifest_path, "r", encoding="utf-8") as yf:
        manifest = yaml.safe_load(yf)

    backfills = manifest.get("backfills", [])
    folder_to_pid: Dict[str, str] = {}

    for entry in backfills:
        folder = entry.get("folder")
        pid = entry.get("projectIdToAssign", "")
        if folder and pid:
            norm = folder.rstrip("/")
            folder_to_pid[norm] = pid

    print(f"Loaded {len(folder_to_pid)} workspace-to-project mappings from manifest.")

    # 1. Load agyhub_summaries_proto.pb
    agy_path = os.path.join(dest_dir, "agyhub_summaries_proto.pb")
    has_proto = os.path.isfile(agy_path)
    msg, typedef, sub_typedef = None, None, None
    agy_items_by_id = {}

    if has_proto:
        with open(agy_path, "rb") as f:
            agy_data = f.read()
        msg, typedef = blackboxprotobuf.decode_message(agy_data)

        # Ensure field 18 typedef is present in nested structure
        f17_typedef = typedef['1']['message_typedef']['2']['message_typedef']['17']['message_typedef']
        if '18' not in f17_typedef:
            f17_typedef['18'] = {'type': 'bytes', 'name': '18'}

        sub_typedef = typedef['1']['message_typedef']['2']['message_typedef']

        for item in msg.get('1', []):
            cid_bytes = item.get('1')
            if cid_bytes:
                agy_items_by_id[cid_bytes] = item

    # 2. Query conversations in SQLite
    cur = con.cursor()
    all_convs = cur.execute("SELECT conversation_id, workspace_uris, project_id, raw_summary FROM conversation_summaries").fetchall()

    updated_count = 0
    already_assigned = 0
    skipped_count = 0

    for cid_str, uris_raw, current_pid, raw_blob in all_convs:
        cid_bytes = cid_str.encode("utf-8")
        try:
            uris = json.loads(uris_raw)
            u = uris[0] if uris else ""
            norm = u.replace("file://", "").rstrip("/")
        except Exception:
            norm = ""

        target_pid = folder_to_pid.get(norm)
        if not target_pid:
            skipped_count += 1
            continue

        if current_pid == target_pid:
            already_assigned += 1
            continue

        pid_bytes = target_pid.encode("utf-8")
        updated_raw = None

        # Update protobuf map entry
        if has_proto and cid_bytes in agy_items_by_id:
            item = agy_items_by_id[cid_bytes]
            f17 = item['2'].setdefault('17', {})
            f17['18'] = pid_bytes
            updated_raw = blackboxprotobuf.encode_message(item['2'], sub_typedef)
        elif raw_blob:
            try:
                smsg, stypedef = blackboxprotobuf.decode_message(raw_blob)
                stypedef.setdefault('17', {}).setdefault('message_typedef', {})['18'] = {'type': 'bytes', 'name': '18'}
                smsg.setdefault('17', {})['18'] = pid_bytes
                updated_raw = blackboxprotobuf.encode_message(smsg, stypedef)
            except Exception:
                updated_raw = raw_blob

        # Update SQLite
        if updated_raw:
            cur.execute(
                "UPDATE conversation_summaries SET project_id = ?, raw_summary = ? WHERE conversation_id = ?",
                (target_pid, updated_raw, cid_str)
            )
        else:
            cur.execute(
                "UPDATE conversation_summaries SET project_id = ? WHERE conversation_id = ?",
                (target_pid, cid_str)
            )
        updated_count += 1

    con.commit()
    print(f"✓ SQLite: Updated {updated_count} conversations ({already_assigned} already up-to-date).")

    # 3. Write back agyhub_summaries_proto.pb
    if has_proto and msg and typedef:
        print("Encoding updated agyhub_summaries_proto.pb...")
        encoded = blackboxprotobuf.encode_message(msg, typedef)
        with open(agy_path, "wb") as f:
            f.write(encoded)
        print(f"✓ Wrote {len(encoded)} bytes to agyhub_summaries_proto.pb.")

    return updated_count, already_assigned, skipped_count

def main():
    args = parse_args()
    print("==================================================")
    print("   Antigravity 2.5.x -> 2.6.0 Migration Executor")
    print("==================================================")
    print(f"Manifest    : {args.manifest}")
    print(f"Source      : {args.old_ide_dir}")
    print(f"Destination : {args.destination_dir}\n")

    if not os.path.isfile(args.manifest):
        print(f"ERROR: Manifest file not found: {args.manifest}", file=sys.stderr)
        print("Please run check_and_catalog.py first to generate the manifest.", file=sys.stderr)
        sys.exit(1)

    check_process_not_running()

    db_path = os.path.join(args.destination_dir, "conversation_summaries.db")
    agy_path = os.path.join(args.destination_dir, "agyhub_summaries_proto.pb")

    if not args.skip_backup:
        print("\n--- Safety Backups ---")
        if os.path.isfile(db_path):
            shutil.copy2(db_path, db_path + ".bak")
            print(f"✓ Backup created: {db_path}.bak")
        if os.path.isfile(agy_path):
            shutil.copy2(agy_path, agy_path + ".bak")
            print(f"✓ Backup created: {agy_path}.bak")

    # 1. Copy missing physical files
    copy_missing_files(args.old_ide_dir, args.destination_dir)

    # 2. Open DB connection
    con = sqlite3.connect(db_path)

    # 3. Handle unmarked conversations if requested
    if args.migrate_unmarked:
        handle_unmarked_conversations(args.old_ide_dir, args.destination_dir, con)

    # 4. Apply project backfills from manifest
    updated, already, skipped = apply_project_backfill(args.destination_dir, args.manifest, con)
    con.close()

    print("\n==================================================")
    print("               Migration Summary")
    print("==================================================")
    print(f"Conversations Updated       : {updated}")
    print(f"Conversations Already Linked: {already}")
    print(f"Conversations Skipped/Flat  : {skipped}")
    print("\n✓ Backfill complete! You can now start Antigravity Desktop.")

if __name__ == "__main__":
    main()
