def get_process_cmdline(pid: str) -> str:
    # Membaca argumen baris perintah dari PID pada Linux (/proc) maupun macOS (ps)
    proc_cmdline = f"/proc/{pid}/cmdline"
    if os.path.isfile(proc_cmdline):
        try:
            with open(proc_cmdline, "r", errors="replace") as f:
                return f.read().replace("\0", " ").strip()
        except Exception:
            pass
    try:
        res = subprocess.run(["ps", "-p", pid, "-o", "command="], stdout=subprocess.PIPE, stderr=subprocess.DEVNULL, text=True)
        if res.returncode == 0:
            return res.stdout.strip()
    except Exception:
        pass
    return ""


def check_process_not_running(allow_running: bool = False):
    # Memastikan proses Antigravity Desktop/IDE sudah tertutup agar cache protobuf di RAM tidak menimpa hasil migrasi
    if allow_running:
        print("⚠️  WARNING: --run-even-antigravity-active specified. Bypassing active process check.")
        print("    Ensure Desktop is not running to avoid background clobbering of protobuf/db cache.")
        return

    try:
        if sys.platform == "win32":
            res = subprocess.run(["tasklist"], stdout=subprocess.PIPE, text=True, errors="replace")
            if "Antigravity.exe" in res.stdout or "antigravity.exe" in res.stdout:
                print("ERROR: Antigravity Desktop is currently running!", file=sys.stderr)
                print("Please quit Antigravity Desktop completely before running execute_backfill.py.", file=sys.stderr)
                print("If this is a false positive, re-run with: --run-even-antigravity-active", file=sys.stderr)
                sys.exit(1)
        else:
            res = subprocess.run(["pgrep", "-if", "antigravity"], stdout=subprocess.PIPE, text=True)
            if res.returncode == 0:
                pids = res.stdout.strip().splitlines()
                desktop_running = False
                trigger_info = ""
                orphan_hub_pids: List[int] = []
                my_pid = str(os.getpid())

                for pid in pids:
                    if pid == my_pid:
                        continue
                    cmd = get_process_cmdline(pid)
                    if not cmd:
                        continue
                    # Abaikan proses crashpad_handler yang sering tertinggal di macOS setelah jendela aplikasi ditutup
                    if "chrome_crashpad_handler" in cmd or "crashpad-handler" in cmd:
                        continue
                    if "remote-control" in cmd and "serve" in cmd:
                        continue
                    if "execute_backfill" in cmd or "check_and_catalog" in cmd:
                        continue
                    if "antigravity-acp" in cmd or "agy_acp_server" in cmd or "localharness_external" in cmd:
                        continue
                    # Pisahkan daemon latar belakang agy --hub / language_server dari proses antarmuka utama Electron
                    if ("agy --hub" in cmd or "language_server" in cmd) and "Electron" not in cmd:
                        try:
                            orphan_hub_pids.append(int(pid))
                        except ValueError:
                            pass
                        continue
                    desktop_running = True
                    trigger_info = f"PID {pid} ({cmd[:80]}...)"
                    break

                if desktop_running:
                    print("ERROR: Antigravity Desktop/IDE appears to be running!", file=sys.stderr)
                    if trigger_info:
                        print(f"Triggered by process: {trigger_info}", file=sys.stderr)
                    print("Please quit Antigravity Desktop completely before running execute_backfill.py.", file=sys.stderr)
                    print("Or use --copy-files-only to safely copy missing brain/ folders while Desktop is open.", file=sys.stderr)
                    print("If this is a false positive, re-run with: --run-even-antigravity-active", file=sys.stderr)
                    sys.exit(1)

                # Jika jendela utama Electron sudah ditutup tetapi daemon agy --hub masih tertinggal di latar belakang, hentikan secara otomatis
                if orphan_hub_pids:
                    print(f"Stopping {len(orphan_hub_pids)} lingering background agy --hub daemon(s): {orphan_hub_pids}...")
                    for hpid in orphan_hub_pids:
                        try:
                            os.kill(hpid, signal.SIGTERM)
                        except OSError:
                            pass
                    time.sleep(1.0)
    except FileNotFoundError:
        pass
    print("✓ Process check passed: Antigravity Desktop is closed.")


def backup_sqlite_db(src_db_path: str, bak_db_path: str) -> None:
    # Mencadangkan database SQLite secara konsisten termasuk transaksi yang masih berada di file -wal
    src_con = sqlite3.connect(src_db_path)
    dst_con = sqlite3.connect(bak_db_path)
    with dst_con:
        src_con.backup(dst_con)
    dst_con.close()
    src_con.close()


def extract_title_from_task_md(brain_dir: str, cid: str) -> str:
    # Mengambil judul dari baris heading pertama di brain/<cid>/task.md jika title dan preview kosong di SQLite
    tmd = os.path.join(brain_dir, cid, "task.md")
    if not os.path.isfile(tmd):
        return ""
    try:
        with open(tmd, "r", encoding="utf-8", errors="ignore") as f:
            for line in f:
                s = line.strip()
                if s.startswith("#"):
                    s = s.lstrip("#").strip()
                    if s.lower().startswith("task:"):
                        s = s[5:].strip()
                    return s[:120]
    except Exception:
        pass
    return ""


def copy_missing_files(old_dir: str, dest_dir: str):
    # Menyalin serta menyinkronkan file percakapan (.db dan .pb), brain/<id>, dan implicit/ yang belum ada atau lebih baru di direktori sumber
    print("\n--- 1. Copying & Syncing Missing or Newer Files ---")
    old_brain_dir = os.path.join(old_dir, "brain")
    dest_brain_dir = os.path.join(dest_dir, "brain")
    os.makedirs(dest_brain_dir, exist_ok=True)

    copied_brains = 0
    updated_brains = 0
    updated_brain_files = 0
    brains_with_newer_transcript: Set[str] = set()

    if os.path.isdir(old_brain_dir):
        # Hanya memproses folder percakapan berformat UUID (mengabaikan .DS_Store atau tempmediaStorage)
        old_brains = {
            b for b in os.listdir(old_brain_dir)
            if UUID_PATTERN.match(b) and os.path.isdir(os.path.join(old_brain_dir, b))
        }
        dest_brains = {
            b for b in os.listdir(dest_brain_dir)
            if UUID_PATTERN.match(b) and os.path.isdir(os.path.join(dest_brain_dir, b))
        }
        missing_brains = old_brains - dest_brains

        for b in sorted(missing_brains):
            src_path = os.path.join(old_brain_dir, b)
            dst_path = os.path.join(dest_brain_dir, b)
            shutil.copytree(src_path, dst_path, dirs_exist_ok=True)
            copied_brains += 1

        # Untuk folder brain/<id> yang sudah ada di kedua tempat (kasus migrasi bolak-balik .antigravity -> .antigravity-ide -> .antigravity),
        # salin file yang belum ada atau yang memiliki ukuran lebih besar / waktu modifikasi lebih baru di sumber
        for b in sorted(old_brains & dest_brains):
            src_b = os.path.join(old_brain_dir, b)
            dst_b = os.path.join(dest_brain_dir, b)
            src_tr = os.path.join(src_b, ".system_generated", "logs", "transcript.jsonl")
            dst_tr = os.path.join(dst_b, ".system_generated", "logs", "transcript.jsonl")
            if os.path.isfile(src_tr) and (not os.path.isfile(dst_tr) or os.stat(src_tr).st_size > os.stat(dst_tr).st_size):
                brains_with_newer_transcript.add(b)

            folder_touched = False
            for root, _, files in os.walk(src_b):
                rel_root = os.path.relpath(root, src_b)
                target_root = dst_b if rel_root == "." else os.path.join(dst_b, rel_root)
                for fn in files:
                    if fn == ".DS_Store":
                        continue
                    src_fp = os.path.join(root, fn)
                    dst_fp = os.path.join(target_root, fn)
                    try:
                        src_st = os.stat(src_fp)
                        need_copy = False
                        if not os.path.exists(dst_fp):
                            need_copy = True
                        else:
                            dst_st = os.stat(dst_fp)
                            if src_st.st_size > dst_st.st_size or src_st.st_mtime > dst_st.st_mtime + 60:
                                need_copy = True
                        if need_copy:
                            os.makedirs(target_root, exist_ok=True)
                            shutil.copy2(src_fp, dst_fp)
                            updated_brain_files += 1
                            folder_touched = True
                    except Exception:
                        pass
            if folder_touched:
                updated_brains += 1

    print(f"✓ Brain folders: copied {copied_brains} missing folders, synced {updated_brain_files} newer/missing files across {updated_brains} existing folders.")

    old_conv_dir = os.path.join(old_dir, "conversations")
    dest_conv_dir = os.path.join(dest_dir, "conversations")
    os.makedirs(dest_conv_dir, exist_ok=True)

    copied_convs = 0
    updated_convs = 0
    if os.path.isdir(old_conv_dir):
        old_files = {f for f in os.listdir(old_conv_dir) if f.endswith((".db", ".pb"))}
        dest_files = {f for f in os.listdir(dest_conv_dir) if f.endswith((".db", ".pb"))}
        missing_files = old_files - dest_files

        for f in sorted(missing_files):
            src_f = os.path.join(old_conv_dir, f)
            dst_f = os.path.join(dest_conv_dir, f)
            shutil.copy2(src_f, dst_f)
            if f.endswith(".db"):
                for suffix in ("-wal", "-shm"):
                    if os.path.isfile(src_f + suffix) and not os.path.isfile(dst_f + suffix):
                        shutil.copy2(src_f + suffix, dst_f + suffix)
            copied_convs += 1

        # Periksa file percakapan yang sudah ada di tujuan namun tertinggal di snapshot lama (ukuran sumber lebih besar atau transkrip sumber lebih baru)
        for f in sorted(old_files & dest_files):
            cid = f[:-3]
            src_f = os.path.join(old_conv_dir, f)
            dst_f = os.path.join(dest_conv_dir, f)
            try:
                src_st = os.stat(src_f)
                dst_st = os.stat(dst_f)
                # Untuk file .pb, selisih 39 byte normal karena penambahan field project_id oleh migrator 2.6.0
                is_stale_pb = f.endswith(".pb") and (src_st.st_size > dst_st.st_size + 100 or cid in brains_with_newer_transcript)
                is_stale_db = f.endswith(".db") and (src_st.st_size > dst_st.st_size and src_st.st_mtime > dst_st.st_mtime + 60)
                if is_stale_pb or is_stale_db:
                    shutil.copy2(src_f, dst_f)
                    updated_convs += 1
            except Exception:
                pass

    print(f"✓ Conversation files: copied {copied_convs} missing files, updated {updated_convs} stale files from newer source.")

    # Sinkronkan juga direktori implicit/ jika ada file yang belum tersalin atau lebih baru di sumber
    old_imp_dir = os.path.join(old_dir, "implicit")
    dest_imp_dir = os.path.join(dest_dir, "implicit")
    if os.path.isdir(old_imp_dir):
        os.makedirs(dest_imp_dir, exist_ok=True)
        imp_synced = 0
        for fn in sorted(os.listdir(old_imp_dir)):
            if fn.startswith("."):
                continue
            src_fp = os.path.join(old_imp_dir, fn)
            dst_fp = os.path.join(dest_imp_dir, fn)
            if os.path.isfile(src_fp):
                if not os.path.exists(dst_fp) or os.stat(src_fp).st_size > os.stat(dst_fp).st_size or os.stat(src_fp).st_mtime > os.stat(dst_fp).st_mtime + 60:
                    shutil.copy2(src_fp, dst_fp)
                    imp_synced += 1
        if imp_synced > 0:
            print(f"✓ Implicit context: synced {imp_synced} missing/newer files.")


def consolidate_project_configs(projects_config_dir: str, folder_to_pid: Dict[str, str]) -> None:
    """Menyatukan definisi proyek di ~/.gemini/config/projects/*.json agar mencakup path symlink, realpath, dan variasi encoding."""
    if not os.path.isdir(projects_config_dir):
        return

    print("\n--- 2. Consolidating Project Resource URIs (Symlinks & Encoding) ---")
    canonical_pids = set(folder_to_pid.values())

    # Mengumpulkan semua path (baik symlink maupun realpath) untuk setiap UUID proyek kanonis
    pid_to_paths: Dict[str, Set[str]] = {}
    for folder, pid in folder_to_pid.items():
        pid_to_paths.setdefault(pid, set()).add(folder)
        rpath = resolve_real_workspace_path(folder)
        if rpath:
            pid_to_paths[pid].add(rpath)

    # Memindai seluruh file JSON proyek yang ada saat ini
    existing_docs: Dict[str, Dict] = {}
    for pfile in sorted(glob.glob(os.path.join(projects_config_dir, "*.json"))):
        try:
            with open(pfile, "r", encoding="utf-8") as pf:
                doc = json.load(pf)
            pid = doc.get("id", "")
            if pid:
                existing_docs[pid] = doc
                for res in doc.get("projectResources", {}).get("resources", []):
                    raw_u = res.get("gitFolder", {}).get("folderUri") or res.get("folderUri") or ""
                    norm_u = normalize_workspace_uri(raw_u)
                    if norm_u:
                        rpath = resolve_real_workspace_path(norm_u)
                        # Jika proyek ini adalah duplikat yang realpath-nya mengarah ke proyek kanonis, gabungkan path-nya
                        target_pid = folder_to_pid.get(norm_u) or folder_to_pid.get(rpath) or pid
                        pid_to_paths.setdefault(target_pid, set()).add(norm_u)
                        if rpath:
                            pid_to_paths[target_pid].add(rpath)
        except Exception:
            pass

    updated_files = 0
    removed_dups = 0

    for pid, doc in list(existing_docs.items()):
        pfile = os.path.join(projects_config_dir, f"{pid}.json")
        # Hapus proyek duplikat yang seluruh path-nya sudah digabungkan ke proyek kanonis lain
        if pid not in canonical_pids and pid != "default-cli-project":
            # Periksa apakah realpath proyek ini sudah diwakili oleh salah satu canonical_pids
            res_list = doc.get("projectResources", {}).get("resources", [])
            mapped_elsewhere = False
            for res in res_list:
                raw_u = res.get("gitFolder", {}).get("folderUri") or res.get("folderUri") or ""
                norm_u = normalize_workspace_uri(raw_u)
                rpath = resolve_real_workspace_path(norm_u)
                c_pid = folder_to_pid.get(norm_u) or folder_to_pid.get(rpath)
                if c_pid and c_pid != pid:
                    mapped_elsewhere = True
                    break
            if mapped_elsewhere and os.path.isfile(pfile):
                os.remove(pfile)
                removed_dups += 1
                continue

        if pid not in pid_to_paths:
            continue

        resources = doc.setdefault("projectResources", {}).setdefault("resources", [])
        existing_uris: Set[str] = set()
        for res in resources:
            u = res.get("gitFolder", {}).get("folderUri") or res.get("folderUri") or ""
            if u:
                existing_uris.add(u)

        added = False
        for path_item in sorted(pid_to_paths[pid]):
            for uri_var in build_uri_variants(path_item):
                if uri_var not in existing_uris:
                    resources.append({"folderUri": uri_var})
                    existing_uris.add(uri_var)
                    added = True

        # Bersihkan akhiran angka duplikat seperti ' 2' pada nama proyek kanonis jika ada
        clean_name = urllib.parse.unquote(doc.get("name", "")).strip()
        if clean_name != doc.get("name", ""):
            doc["name"] = clean_name
            added = True

        if added:
            with open(pfile, "w", encoding="utf-8") as pf:
                json.dump(doc, pf, indent=2, ensure_ascii=False)
            updated_files += 1

    print(f"✓ Updated {updated_files} project config files and removed {removed_dups} duplicate project configs.")


def handle_unmarked_conversations(old_dir: str, dest_dir: str, con: sqlite3.Connection):
    """Mendaftarkan sesi dari direktori lama yang belum memiliki file penanda .done ke dalam SQLite."""
    print("\n--- (Experimental) Handling Unmarked Conversations ---")
    old_conv_dir = os.path.join(old_dir, "conversations")
    if not os.path.isdir(old_conv_dir):
        return

    old_convs = {f[:-3] for f in os.listdir(old_conv_dir) if f.endswith((".db", ".pb"))}
    old_dones = {f[1:-5] for f in os.listdir(old_conv_dir) if f.startswith(".") and f.endswith(".done")}
    unmarked = old_convs - old_dones

    if not unmarked:
        print("No unmarked conversations found.")
        return

    print(f"Found {len(unmarked)} conversations without .done marker.")
    cur = con.cursor()
    newly_indexed = 0

    for cid in sorted(unmarked):
        exists = cur.execute("SELECT 1 FROM conversation_summaries WHERE conversation_id = ?", (cid,)).fetchone()
        if not exists:
            cur.execute("""
                INSERT INTO conversation_summaries (conversation_id, title, preview, last_modified_time, last_user_input_time, workspace_uris)
                VALUES (?, '', '', datetime('now'), datetime('now'), '[]')
            """, (cid,))
            newly_indexed += 1

        done_file = os.path.join(old_conv_dir, f".{cid}.done")
        try:
            with open(done_file, "a"):
                os.utime(done_file, None)
        except Exception:
            pass

    con.commit()
    print(f"Indexed {newly_indexed} unmarked conversations into SQLite.")


def parse_sqlite_timestamp(ts_str: str) -> float:
    # Mengubah string timestamp ISO dari SQLite menjadi epoch seconds (UTC)
    if not ts_str:
        return 0.0
    try:
        dt = datetime.datetime.fromisoformat(ts_str.replace("Z", "+00:00"))
        if dt.tzinfo is None:
            dt = dt.replace(tzinfo=datetime.timezone.utc)
        return dt.timestamp()
    except Exception:
        return 0.0


def ensure_annotation_title(annotations_dir: str, cid: str, title: str, fallback_epoch: float) -> bool:
    # Menyimpan field title:"..." ke dalam annotations/<cid>.pbtxt agar agy --hub tidak menghapus judul saat sesi dibuka
    if not title:
        return False
    os.makedirs(annotations_dir, exist_ok=True)
    ann_path = os.path.join(annotations_dir, f"{cid}.pbtxt")
    esc_title = title.replace("\\", "\\\\").replace('"', '\\"').replace("\n", " ").strip()
    try:
        if os.path.isfile(ann_path):
            with open(ann_path, "r", encoding="utf-8", errors="ignore") as f:
                content = f.read()
            if 'title:"' in content or 'title: "' in content:
                return False
            new_content = f'title:"{esc_title}"  {content.lstrip()}'
            with open(ann_path, "w", encoding="utf-8") as f:
                f.write(new_content)
            return True
        else:
            sec = int(fallback_epoch) if fallback_epoch > 0 else int(time.time())
            with open(ann_path, "w", encoding="utf-8") as f:
                f.write(f'title:"{esc_title}"  last_user_view_time:{{seconds:{sec}  nanos:0}}')
            return True
    except Exception:
        return False


def ensure_trajectory_project_id(conv_dir: str, cid: str, pid: str) -> bool:
    # Menyuntikkan field 18 (project_id) ke dalam file conversations/<cid>.db atau .pb agar agy --hub tidak mereset project_id saat sesi diklik
    if not pid or pid in ("", "default-cli-project", "outside-of-project"):
        return False
    pid_bytes = pid.encode("utf-8")
    field18_wire = b"\x92\x01" + bytes([len(pid_bytes)]) + pid_bytes

    db_file = os.path.join(conv_dir, f"{cid}.db")
    if os.path.isfile(db_file):
        try:
            c = sqlite3.connect(db_file)
            row = c.execute("SELECT data FROM trajectory_metadata_blob WHERE id = 'main'").fetchone()
            if row and row[0]:
                blob = row[0]
                if field18_wire not in blob[-120:]:
                    c.execute("UPDATE trajectory_metadata_blob SET data = ? WHERE id = 'main'", (blob + field18_wire,))
                    c.commit()
                    c.close()
                    return True
            c.close()
        except Exception:
            pass

    pb_file = os.path.join(conv_dir, f"{cid}.pb")
    if os.path.isfile(pb_file):
        try:
            from cryptography.hazmat.primitives.ciphers.aead import AESGCM
            aes = AESGCM(b"safeCodeiumworldKeYsecretBalloon")
            with open(pb_file, "rb") as f:
                raw_enc = f.read()
            if len(raw_enc) > 28:
                nonce = raw_enc[:12]
                pt = aes.decrypt(nonce, raw_enc[12:], None)
                if field18_wire not in pt[-120:]:
                    # Field 7 pada level teratas file .pb adalah trajectory_metadata_blob (wire tag 0x3a)
                    f7_patch = b"\x3a" + bytes([len(field18_wire)]) + field18_wire
                    new_ct = aes.encrypt(nonce, pt + f7_patch, None)
                    with open(pb_file, "wb") as f:
                        f.write(nonce + new_ct)
                    return True
        except Exception:
            pass
    return False


def apply_project_backfill(
    dest_dir: str,
    projects_config_dir: str,
    manifest_path: str,
    con: sqlite3.Connection,
    old_dir: str = ""
):
    # Memperbarui project_id (field 17.18), title (field 15.1), dan waktu modifikasi (field 3) pada SQLite serta agyhub_summaries_proto.pb
    import blackboxprotobuf

    with open(manifest_path, "r", encoding="utf-8") as yf:
        manifest = yaml.safe_load(yf)

    backfills = manifest.get("backfills", [])
    folder_to_pid: Dict[str, str] = {}

    for entry in backfills:
        folder = entry.get("folder")
        pid = entry.get("projectIdToAssign", "")
        if folder and pid and pid not in ("", "default-cli-project", "outside-of-project"):
            norm = normalize_workspace_uri(folder)
            if norm:
                folder_to_pid[norm] = pid
                rpath = resolve_real_workspace_path(norm)
                if rpath:
                    folder_to_pid[rpath] = pid

    # Konsolidasikan file ~/.gemini/config/projects/*.json terlebih dahulu
    consolidate_project_configs(projects_config_dir, folder_to_pid)

    print("\n--- 3. Applying Project, Title & Timestamp Backfill ---")
    print(f"Loaded {len(folder_to_pid)} workspace-to-project path mappings (including resolved symlinks).")

    agy_path = os.path.join(dest_dir, "agyhub_summaries_proto.pb")
    has_proto = os.path.isfile(agy_path)
    msg, typedef = None, None
    all_sub_typedefs: Dict[str, Dict] = {}
    agy_items_by_id = {}

    if has_proto:
        with open(agy_path, "rb") as f:
            agy_data = f.read()
        msg, typedef = blackboxprotobuf.decode_message(agy_data)

        f2_entry = typedef['1']['message_typedef']['2']
        all_sub_typedefs['2'] = f2_entry['message_typedef']
        for alt_k, alt_td in f2_entry.get('alt_typedefs', {}).items():
            all_sub_typedefs[f'2-{alt_k}'] = alt_td

        # Memastikan definisi tipe untuk field 17.18 (project_id) dan field 15.1 (title 2.6.0) tersedia di seluruh varian skema protobuf
        for std in all_sub_typedefs.values():
            f17_typedef = std.setdefault('17', {'type': 'message', 'message_typedef': {}, 'name': ''})['message_typedef']
            if '18' not in f17_typedef:
                f17_typedef['18'] = {'type': 'bytes', 'name': ''}

            f15_typedef = std.setdefault('15', {'type': 'message', 'message_typedef': {}, 'name': ''})['message_typedef']
            if '1' not in f15_typedef:
                f15_typedef['1'] = {'type': 'bytes', 'name': ''}

        for item in msg.get('1', []):
            cid_bytes = item.get('1')
            if cid_bytes:
                agy_items_by_id[cid_bytes] = item

    cur = con.cursor()
    all_convs = cur.execute(
        "SELECT conversation_id, workspace_uris, project_id, title, preview, last_modified_time, raw_summary FROM conversation_summaries"
    ).fetchall()

    updated_count = 0
    already_assigned = 0
    skipped_count = 0
    ann_patched = 0
    traj_patched = 0

    known_paths = list(folder_to_pid.keys())
    dest_brain_dir = os.path.join(dest_dir, "brain")
    dest_ann_dir = os.path.join(dest_dir, "annotations")
    dest_conv_dir = os.path.join(dest_dir, "conversations")
    old_conv_dir = os.path.join(old_dir, "conversations") if old_dir else ""

    for cid_str, uris_raw, current_pid, current_title, current_preview, current_lmt, raw_blob in all_convs:
        cid_bytes = cid_str.encode("utf-8")
        current_title = current_title or ""
        current_preview = current_preview or ""
        current_lmt = current_lmt or ""

        try:
            uris = json.loads(uris_raw)
            u = uris[0] if uris else ""
            norm = normalize_workspace_uri(u)
        except Exception:
            norm = ""

        inferred_from_transcript = False
        if not norm:
            tpath = os.path.join(dest_brain_dir, cid_str, ".system_generated", "logs", "transcript.jsonl")
            norm = infer_workspace_from_transcript(tpath, known_paths)
            if norm:
                inferred_from_transcript = True

        rpath = resolve_real_workspace_path(norm)
        target_pid = folder_to_pid.get(norm) or folder_to_pid.get(rpath) or current_pid
        new_title = current_title if current_title else current_preview
        if not new_title:
            new_title = extract_title_from_task_md(dest_brain_dir, cid_str)
        new_preview = current_preview if current_preview else new_title

        # Periksa apakah waktu modifikasi di direktori sumber (antigravity-ide) lebih baru daripada yang tercatat di SQLite
        db_epoch = parse_sqlite_timestamp(current_lmt)
        newer_mtime: Optional[float] = None
        if old_conv_dir and os.path.isdir(old_conv_dir):
            for ext in (".pb", ".db"):
                cand = os.path.join(old_conv_dir, f"{cid_str}{ext}")
                if os.path.isfile(cand):
                    st_m = os.stat(cand).st_mtime
                    if st_m > db_epoch + 60:
                        newer_mtime = st_m
                    break

        # Pastikan file annotations/<cid>.pbtxt dan conversations/<cid>.db/.pb menyimpan title serta project_id permanen
        if new_title and ensure_annotation_title(dest_ann_dir, cid_str, new_title, newer_mtime or db_epoch):
            ann_patched += 1
        if target_pid and ensure_trajectory_project_id(dest_conv_dir, cid_str, target_pid):
            traj_patched += 1

        pid_needs_update = bool(target_pid and target_pid != current_pid and target_pid not in ("", "default-cli-project", "outside-of-project"))
        title_needs_update = bool(new_title and new_title != current_title)
        mtime_needs_update = newer_mtime is not None

        if not pid_needs_update and not title_needs_update and not mtime_needs_update and not inferred_from_transcript:
            if target_pid and target_pid not in ("", "default-cli-project", "outside-of-project"):
                already_assigned += 1
            else:
                skipped_count += 1
            continue

        final_pid = target_pid if pid_needs_update else current_pid
        final_lmt = (
            datetime.datetime.fromtimestamp(newer_mtime, tz=datetime.timezone.utc).strftime("%Y-%m-%d %H:%M:%S.%f+00:00")
            if newer_mtime is not None else current_lmt
        )
        pid_bytes = final_pid.encode("utf-8") if final_pid else b""
        title_bytes = new_title.encode("utf-8") if new_title else b""
        updated_raw: Optional[bytes] = None

        # Memperbarui entri pada struktur protobuf agyhub (field 17.18 untuk project_id, field 15.1 untuk title, dan field 3 untuk waktu modifikasi)
        if has_proto and cid_bytes in agy_items_by_id:
            item = agy_items_by_id[cid_bytes]
            pkey = next((k for k in item if k == '2' or k.startswith('2-')), None)
            if pkey and isinstance(item.get(pkey), dict):
                payload = item[pkey]
                if pid_bytes:
                    f17 = payload.setdefault('17', {})
                    f17['18'] = pid_bytes
                if title_bytes:
                    f15 = payload.setdefault('15', {})
                    f15['1'] = title_bytes
                if newer_mtime is not None and isinstance(payload.get('3'), dict):
                    payload['3']['1'] = int(newer_mtime)
                    payload['3']['2'] = int((newer_mtime % 1) * 1e9)
                if pkey in all_sub_typedefs:
                    updated_raw = blackboxprotobuf.encode_message(payload, all_sub_typedefs[pkey])
        elif raw_blob:
            try:
                smsg, stypedef = blackboxprotobuf.decode_message(raw_blob)
                if pid_bytes:
                    stypedef.setdefault('17', {'type': 'message', 'message_typedef': {}, 'name': ''}).setdefault('message_typedef', {})['18'] = {'type': 'bytes', 'name': ''}
                    smsg.setdefault('17', {})['18'] = pid_bytes
                if title_bytes:
                    stypedef.setdefault('15', {'type': 'message', 'message_typedef': {}, 'name': ''}).setdefault('message_typedef', {})['1'] = {'type': 'bytes', 'name': ''}
                    smsg.setdefault('15', {})['1'] = title_bytes
                if newer_mtime is not None and isinstance(smsg.get('3'), dict):
                    smsg['3']['1'] = int(newer_mtime)
                    smsg['3']['2'] = int((newer_mtime % 1) * 1e9)
                updated_raw = blackboxprotobuf.encode_message(smsg, stypedef)
            except Exception:
                updated_raw = raw_blob

        new_uris_raw = json.dumps([f"file://{urllib.parse.quote(norm, safe='/~')}"]) if inferred_from_transcript else uris_raw

        if updated_raw:
            cur.execute(
                "UPDATE conversation_summaries SET project_id = ?, title = ?, preview = ?, last_modified_time = ?, workspace_uris = ?, raw_summary = ? WHERE conversation_id = ?",
                (final_pid, new_title, new_preview, final_lmt, new_uris_raw, updated_raw, cid_str)
            )
        else:
            cur.execute(
                "UPDATE conversation_summaries SET project_id = ?, title = ?, preview = ?, last_modified_time = ?, workspace_uris = ? WHERE conversation_id = ?",
                (final_pid, new_title, new_preview, final_lmt, new_uris_raw, cid_str)
            )
        updated_count += 1

    con.commit()
    print(f"✓ SQLite: Updated {updated_count} conversations ({already_assigned} already up-to-date, {skipped_count} unassociated).")
    print(f"✓ Persistence: Patched {ann_patched} annotations/*.pbtxt titles and {traj_patched} conversations/*.db|*.pb project IDs.")

    # Menulis ulang agyhub_summaries_proto.pb jika ada perubahan
    if has_proto and msg and typedef and updated_count > 0:
        print("Encoding updated agyhub_summaries_proto.pb...")
        encoded = blackboxprotobuf.encode_message(msg, typedef)
        with open(agy_path, "wb") as f:
            f.write(encoded)
        print(f"✓ Wrote {len(encoded)} bytes to agyhub_summaries_proto.pb.")
    elif has_proto and updated_count == 0:
        print("✓ Protobuf: No changes needed for agyhub_summaries_proto.pb.")

    return updated_count, already_assigned, skipped_count


def main():
    args = parse_args()
    print("==================================================")
    print("   Antigravity 2.5.x -> 2.6.0 Migration Executor")
    print("==================================================")
    print(f"Manifest        : {args.manifest}")
    print(f"Source          : {args.old_ide_dir}")
    print(f"Destination     : {args.destination_dir}")
    print(f"Projects Config : {args.projects_config_dir}")
    print(f"Copy Files Only : {args.copy_files_only}\n")

    if not args.copy_files_only:
        if not os.path.isfile(args.manifest):
            print(f"ERROR: Manifest file not found: {args.manifest}", file=sys.stderr)
            print("Please run check_and_catalog.py first to generate the manifest.", file=sys.stderr)
            sys.exit(1)
        check_process_not_running(allow_running=args.run_even_antigravity_active)

    db_path = os.path.join(args.destination_dir, "conversation_summaries.db")
    agy_path = os.path.join(args.destination_dir, "agyhub_summaries_proto.pb")

    if not args.copy_files_only and not args.skip_backup:
        print("\n--- Safety Backups ---")
        ts = time.strftime("%Y%m%d_%H%M%S")
        if os.path.isfile(db_path):
            db_bak = f"{db_path}.{ts}.bak"
            backup_sqlite_db(db_path, db_bak)
            print(f"✓ SQLite backup created (WAL-safe): {db_bak}")
        if os.path.isfile(agy_path):
            agy_bak = f"{agy_path}.{ts}.bak"
            shutil.copy2(agy_path, agy_bak)
            print(f"✓ Protobuf backup created: {agy_bak}")
        if os.path.isdir(args.projects_config_dir):
            proj_bak = f"{args.projects_config_dir.rstrip('/')}.{ts}.bak"
            shutil.copytree(args.projects_config_dir, proj_bak, dirs_exist_ok=True)
            print(f"✓ Projects config backup created: {proj_bak}")

    # 1. Menyalin file fisik yang belum ada (brain/<id> dan conversations/*.db/*.pb)
    copy_missing_files(args.old_ide_dir, args.destination_dir)

    if args.copy_files_only:
        print("\n✓ File copy complete (--copy-files-only). SQLite and protobuf caches were not modified.")
        return

    # 2. Membuka koneksi database SQLite untuk pembaruan indeks
    con = sqlite3.connect(db_path)

    # 3. Menangani percakapan tanpa penanda .done jika opsi diaktifkan
    if args.migrate_unmarked:
        handle_unmarked_conversations(args.old_ide_dir, args.destination_dir, con)

    # 4. Menerapkan pemetaan project_id, konsolidasi symlink proyek, pengisian title, dan pembaruan waktu modifikasi dari manifes
    updated, already, skipped = apply_project_backfill(
        args.destination_dir,
        args.projects_config_dir,
        args.manifest,
        con,
        old_dir=args.old_ide_dir
    )
    con.close()

    print("\n==================================================")
    print("               Migration Summary")
    print("==================================================")
    print(f"Conversations Updated       : {updated}")
    print(f"Conversations Already Linked: {already}")
    print(f"Conversations Skipped/Flat  : {skipped}")
    print("\n✓ Backfill complete! You can now start Antigravity Desktop.")


if __name__ == "__main__":
    main()
