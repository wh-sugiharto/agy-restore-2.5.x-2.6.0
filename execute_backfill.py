#!/usr/bin/env python3
"""
execute_backfill.py

Phase 2 of Antigravity 2.5.x to 2.6.0 Migration:
- Reads `scratch_file.yml` generated by `check_and_catalog.py`.
- Copies missing conversations/*.db and *.pb files.
- Copies missing brain/<id> folders faithfully (UUID folders only).
- Consolidates symlinked and URL-encoded project resources in ~/.gemini/config/projects/*.json.
- Backfills project IDs (field 17.18) and missing 2.6.0 titles (field 15.1) into conversation_summaries.db and agyhub_summaries_proto.pb.
- Supports --copy-files-only to sync missing brain/ and conversation files safely without modifying index caches.
- Supports --migrate-unmarked (experimental) to handle sessions without .done markers.
"""

